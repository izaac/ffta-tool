def compute_god_stats(job_id: int, level: int = 8) -> dict[str, int]:
    """Calculates optimal 115% top-roll recruit stats and growths for a job at a given level."""
    st = JOB_STAT_TABLE.get(job_id, JOB_STAT_TABLE[1])
    lvl = max(0, level - 1)
    return {
        "hp": int(st[0] * 1.15 + lvl * st[7]),
        "mp": int(st[1] * 1.15 + lvl * st[13]),
        "speed": int(st[2] * 1.15 + lvl * st[8]),
        "watk": int(st[3] * 1.15 + lvl * st[9]),
        "wdef": int(st[4] * 1.15 + lvl * st[10]),
        "mpow": int(st[5] * 1.15 + lvl * st[11]),
        "mres": int(st[6] * 1.15 + lvl * st[12]),
    }


