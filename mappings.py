def get_unit_name(name_id: int, special_flag: int = 1) -> str:
    """Returns canonical character name from name ID and special character flag."""
    if special_flag == 2:
        return "Marche"
    if special_flag == 8:
        return "Montblanc"
    if 0 <= name_id < len(RECRUIT_NAMES):
        return RECRUIT_NAMES[name_id]
    return f"Unit#{name_id}"


def get_name_id_by_str(name_str: str) -> int | None:
    """Finds first matching name ID for a given name string (case-insensitive)."""
    clean = name_str.strip().lower()
    for idx, name in enumerate(RECRUIT_NAMES):
        if name.lower() == clean:
            return idx
    return None


def generate_random_name(race_id: int, excluded_ids: set[int] | None = None) -> tuple[int, str]:
    """Generates a canonical, race-appropriate random name from the ROM database."""
    import random

    excluded = excluded_ids or set()

    if race_id == 4:
        # Viera: strictly female names (indices 320..499)
        pool = [i for i in range(320, 500) if i not in excluded]
    elif race_id in (2, 3):
        # Bangaa & Nu Mou: prefer exotic names (500..724), fallback to male pool (0..319)
        exotic = [i for i in range(500, len(RECRUIT_NAMES)) if i not in excluded]
        general = [i for i in range(0, 320) if i not in excluded]
        pool = exotic if exotic else general
    else:
        # Hume & Moogle: general male pool (0..319), fallback to exotic (500..724)
        general = [i for i in range(0, 320) if i not in excluded]
        exotic = [i for i in range(500, len(RECRUIT_NAMES)) if i not in excluded]
        pool = general if general else exotic

    if not pool:
        pool = [i for i in range(len(RECRUIT_NAMES)) if i not in excluded] or list(range(len(RECRUIT_NAMES)))

    chosen_id = random.choice(pool)
    return chosen_id, RECRUIT_NAMES[chosen_id]


